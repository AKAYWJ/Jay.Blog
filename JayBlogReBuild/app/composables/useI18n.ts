export const useI18n = () => {
  // SSR 安全：状态提升到 useState，且初值从 Cookie 读取，
  // 保证服务端与客户端的初始渲染语言完全一致，避免 hydration mismatch。
  const localeCookie = useCookie<Locale>('locale', {
    default: () => 'zh-CN' as Locale,
    maxAge: 60 * 60 * 24 * 365 // 1 年
  })
  const locale = useState<Locale>('app:locale', () => localeCookie.value || 'zh-CN')

  const setLocale = (val: Locale, persist = true) => {
    locale.value = val
    if (typeof document !== 'undefined') {
      document.documentElement.lang = val === 'zh-CN' ? 'zh-CN' : 'en'
    }
    if (persist) {
      localeCookie.value = val
      if (typeof localStorage !== 'undefined') {
        localStorage.setItem('locale', val)
      }
    }
  }

  /**
   * 翻译函数
   * - 缺 key 时回退原文（key 字符串本身）
   * - 支持占位符：t('hero.search.tip', { key: 'foo', total: 3 })
   *   对应 "Search \"foo\", 3 results"
   */
  const t = (key: string, params?: Record<string, string | number>): string => {
    let str = messages[locale.value]?.[key] ?? messages['zh-CN']?.[key] ?? key
    if (params) {
      for (const [k, v] of Object.entries(params)) {
        str = str.replace(new RegExp(`\\{${k}\\}`, 'g'), String(v))
      }
    }
    return str
  }

  /** 客户端初始化：localStorage(用户选择) > 浏览器语言；Cookie 用于 SSR 一致渲染 */
  const init = () => {
    if (typeof window === 'undefined') return
    // 以 localStorage 为准（真实持久化的用户选择），与 Cookie 同源，避免 SSR 不一致
    const stored = localStorage.getItem('locale')
    if (stored === 'zh-CN' || stored === 'en-US') {
      if (locale.value !== stored) setLocale(stored, true)
      return
    }
    // 兼容：Cookie 已有但 localStorage 缺失（如用户清理了 localStorage）
    if (localeCookie.value === 'zh-CN' || localeCookie.value === 'en-US') {
      localStorage.setItem('locale', localeCookie.value)
      return
    }
    // 自动嗅探浏览器语言（仅全新访客）
    const browser = navigator.language.toLowerCase()
    if (browser.startsWith('en')) {
      setLocale('en-US', true)
    } else {
      setLocale('zh-CN', true)
    }
  }

  return {
    locale: computed(() => locale.value),
    setLocale,
    t,
    init,
    available: ['zh-CN', 'en-US'] as Locale[]
  }
}
